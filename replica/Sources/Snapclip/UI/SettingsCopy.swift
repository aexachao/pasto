/// Stable identifiers preserve existing settings deep links; ordering is independent.
enum SettingsSection: Int, CaseIterable, Identifiable {
    case general = 0, clipboard = 3, screenshot = 2, shortcuts = 4, privacy = 1, ai = 5
    var id: Int { rawValue }
    var title: String {
        switch self {
        case .general: return SettingsCopy.bilingual("通用", "General")
        case .clipboard: return SettingsCopy.bilingual("剪贴板与历史", "Clipboard & History")
        case .screenshot: return SettingsCopy.bilingual("截图", "Screenshots")
        case .shortcuts: return SettingsCopy.bilingual("快捷键", "Shortcuts")
        case .privacy: return SettingsCopy.bilingual("隐私与权限", "Privacy & Permissions")
        case .ai: return SettingsCopy.bilingual("AI 工具", "AI Tools")
        }
    }
    var icon: String {
        switch self {
        case .general: return "gearshape"
        case .clipboard: return "doc.on.clipboard"
        case .screenshot: return "camera.viewfinder"
        case .shortcuts: return "keyboard"
        case .privacy: return "hand.raised"
        case .ai: return "point.3.connected.trianglepath.dotted"
        }
    }
}

